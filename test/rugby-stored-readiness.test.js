'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {validateCheckin}=require('../src/rugby/checkinValidation');
const {evaluateStoredReadiness}=require('../src/rugby/storedReadiness');
const {evaluateAthleteEligibility}=require('../src/rugby/athleteEligibility');
const today='2026-11-25',yesterday='2026-11-24';
const recovery={sleepHours:7,hydration:'good',sleepQuality:4,physicalFatigue:2,mentalFatigue:2,soreness:2,stress:2,wellbeing:4};
const record=(x={})=>validateCheckin({date:today,readiness:'normal',...x});
const run=(records,age='adult')=>evaluateStoredReadiness({rugbyCheckins:records},'a',today,age);
test('legacy remains compatible',()=>assert.equal(record().recovery,undefined));
test('recovery version server owned',()=>assert.equal(record({recovery}).recovery.scaleVersion,'v1'));
test('reject invalid recovery',()=>assert.throws(()=>record({recovery:{...recovery,sleepHours:25}})));
test('reject forged scale',()=>assert.throws(()=>record({recovery:{...recovery,scaleVersion:'v1'}})));
test('pain refers',()=>assert.equal(run([record({readiness:'pain'})]).status,'REFER'));
test('injury refers',()=>assert.equal(run([record({injuryConcern:true})]).status,'REFER'));
test('fatigue holds',()=>assert.equal(run([record({readiness:'fatigued'})]).status,'HOLD'));
test('team load holds',()=>assert.equal(run([record({teamHighLoad:true})]).status,'HOLD'));
test('stale holds',()=>assert.equal(run([record({date:yesterday})]).status,'HOLD'));
test('future holds',()=>assert.equal(run([record({date:'2026-11-26'})]).status,'HOLD'));
test('duplicate holds',()=>assert.equal(run([record(),record()]).status,'HOLD'));
test('empty holds',()=>assert.equal(run([]).status,'HOLD'));
test('legacy never clears',()=>assert.equal(run([record()]).status,'REVIEW_REQUIRED'));
test('dated descriptive comparison',()=>{const r=run([record({recovery}),record({date:yesterday,recovery:{...recovery,sleepHours:6}})]);assert.equal(r.changes.sleepHours,1);assert.equal(r.comparisonDate,yesterday);assert.equal(r.medicalClearance,false);});
test('unknown age no comparison',()=>assert.equal(run([record({recovery})],'unknown').changes,null));
test('eligibility propagates referral',()=>assert.equal(evaluateAthleteEligibility({rugbyCheckins:[record({readiness:'pain'})]},'a',today,'adult').eligibility.decision,'REFER'));
test('normal readiness cannot grant eligibility',()=>assert.equal(evaluateAthleteEligibility({rugbyCheckins:[record({recovery})]},'a',today,'adult').eligibility.decision,'HOLD'));
