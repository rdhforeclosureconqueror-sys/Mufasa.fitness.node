"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),os=require("node:os"),path=require("node:path"),crypto=require("node:crypto");
const {createWorldBridgeApp}=require("../world-bridge-server");
const {createEventCheckinStore}=require("../src/services/eventCheckinStore");
const {createUserStore}=require("../src/repositories/userStore");
test("real authenticated HTTP guest claim -> seven-day trial -> admin conversion report",async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"milele-verified-http-"));
 const keys=["AUTH_TOKEN_SECRET","PILOT_LOGIN_PASSWORD","LOGIN_SEED_EMAIL","AUTHZ_BOOTSTRAP_SUPER_ADMIN_USER_IDS"];
 const old=Object.fromEntries(keys.map(k=>[k,process.env[k]]));
 Object.assign(process.env,{AUTH_TOKEN_SECRET:"acceptance-real-auth-secret-32-characters",PILOT_LOGIN_PASSWORD:"isolated-admin-password",LOGIN_SEED_EMAIL:"isolated-admin@example.invalid",AUTHZ_BOOTSTRAP_SUPER_ADMIN_USER_IDS:"pilot_admin"});
 t.after(()=>{for(const [k,v]of Object.entries(old)){if(v===undefined)delete process.env[k];else process.env[k]=v;}});
 const server=createWorldBridgeApp({dataDir:dir}).listen(0,"127.0.0.1");
 t.after(async()=>{try{if(server.listening)await new Promise((resolve,reject)=>server.close(e=>e?reject(e):resolve()));}finally{fs.rmSync(dir,{recursive:true,force:true});}assert.equal(fs.existsSync(dir),false);});
 await new Promise((resolve,reject)=>{server.once("listening",resolve);server.once("error",reject)});
 const base="http://127.0.0.1:"+server.address().port;
 async function call(route,{method="GET",token,body}={}){
  const res=await fetch(base+route,{method,headers:{...(token?{authorization:"Bearer "+token}:{}),...(body?{"content-type":"application/json"}:{})},body:body?JSON.stringify(body):undefined});
  return{status:res.status,payload:await res.json().catch(()=>({}))};
 }
 const email="verified-"+crypto.randomBytes(8).toString("hex")+"@example.invalid";
 const registration=await call("/api/auth/register",{method:"POST",body:{name:"Verified Guest",email,password:crypto.randomBytes(16).toString("hex"),entryContext:"run_club"}});
 assert.equal(registration.status,200,JSON.stringify(registration.payload));
 const token=registration.payload.token,userId=registration.payload.user.id;
 const admin=await call("/api/auth/login",{method:"POST",body:{email:"isolated-admin@example.invalid",password:"isolated-admin-password"}});
 assert.equal(admin.status,200,JSON.stringify(admin.payload));
 const event=await call("/api/admin/community/events",{method:"POST",token:admin.payload.token,body:{title:"Verified Yoga",location:"Test Studio",type:"yoga",capacity:4,startAt:"2026-11-14T15:00:00Z",endAt:"2026-11-14T16:00:00Z"}});
 assert.equal(event.status,201,JSON.stringify(event.payload));
 const eventId=event.payload.data.event.eventId;
 const store=createEventCheckinStore({dataDir:dir});
 const pass=store.checkin({event:eventId,name:"Verified Guest",email,before:"Ready"});
 store.reflect({...pass,after:"Relaxed"});
 const url="/api/admin/community/events/"+eventId+"/conversions";
 assert.equal((await call(url)).status,401);
 assert.equal((await call(url,{token})).status,403);
 assert.equal((await call("/api/me/community/guest-check-in/claim",{method:"POST",body:pass})).status,401);
 const claimed=await call("/api/me/community/guest-check-in/claim",{method:"POST",token,body:pass});
 assert.equal(claimed.status,200,JSON.stringify(claimed.payload));
 const rejected=await call("/api/me/trial-access/accept",{method:"POST",token,body:{accepted:false}});
 assert.equal(rejected.status,422);
 const trial=await call("/api/me/trial-access/accept",{method:"POST",token,body:{accepted:true,source:"forged-event",eventId:"fake-event"}});
 assert.equal(trial.status,200,JSON.stringify(trial.payload));
 assert.equal(trial.payload.data.trial.origin.eventId,eventId);
 assert.equal(trial.payload.data.trial.origin.checkInId,pass.id);
 assert.equal(trial.payload.data.trial.paymentRequired,false);
 const again=await call("/api/me/trial-access/accept",{method:"POST",token,body:{accepted:true}});
 assert.equal(again.payload.data.trial.acceptedAt,trial.payload.data.trial.acceptedAt);
 const report=await call(url,{token:admin.payload.token});
 assert.equal(report.status,200,JSON.stringify(report.payload));
 assert.equal(report.payload.data.checkedIn,1);
 assert.equal(report.payload.data.linkedAccounts,1);
 assert.equal(report.payload.data.trialActivations,1);
 assert.equal(report.payload.data.conversionRate,100);
 const saved=createUserStore({userDir:path.join(dir,"users")}).loadUser(userId);
 assert.equal(saved.trialAccess.origin.eventId,eventId);
 assert.equal(JSON.stringify(report.payload).includes(email),false);
});
