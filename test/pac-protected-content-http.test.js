"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),os=require("node:os"),path=require("node:path"),crypto=require("node:crypto");
const {createApp}=require("../server");
async function request(base,url,{method="GET",token,body,cookie,redirect="manual"}={}){
 const response=await fetch(base+url,{method,redirect,headers:{...(token?{authorization:"Bearer "+token}:{}),...(body?{"content-type":"application/json"}:{}),...(cookie?{cookie}:{})},body:body?JSON.stringify(body):undefined});
 return {status:response.status,headers:response.headers,text:await response.text()};
}
test("PAC approved, revoked and unauthorized content requests across real HTTP",async t=>{
 const envKeys=["AUTH_TOKEN_SECRET","PILOT_LOGIN_PASSWORD","LOGIN_SEED_EMAIL","AUTHZ_BOOTSTRAP_SUPER_ADMIN_USER_IDS","BACKEND_PUBLIC_URL"];
 const old=Object.fromEntries(envKeys.map(key=>[key,process.env[key]]));
 Object.assign(process.env,{AUTH_TOKEN_SECRET:"pac-isolated-secret-32-characters-long",PILOT_LOGIN_PASSWORD:"isolated-admin-password",LOGIN_SEED_EMAIL:"isolated-admin@example.invalid",AUTHZ_BOOTSTRAP_SUPER_ADMIN_USER_IDS:"pilot_admin"});
 delete process.env.BACKEND_PUBLIC_URL;
 t.after(()=>{for(const [key,value] of Object.entries(old)){if(value===undefined)delete process.env[key];else process.env[key]=value;}});
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"milele-pac-auth-"));
 const app=createApp({dataDir:dir});
 const server=app.listen(0,"127.0.0.1");
 t.after(async()=>{await new Promise((resolve,reject)=>server.close(error=>error?reject(error):resolve()));fs.rmSync(dir,{recursive:true,force:true});});
 await new Promise(resolve=>server.once("listening",resolve));
 const base="http://127.0.0.1:"+server.address().port;
 const email="pac-"+crypto.randomBytes(6).toString("hex")+"@example.invalid";
 const member=await request(base,"/api/auth/register",{method:"POST",body:{name:"PAC Test Member",email,password:"pac-test-password-123",entryContext:"run_club"}});
 assert.equal(member.status,200,member.text);
 const parsed=JSON.parse(member.text),memberToken=parsed.token,memberId=parsed.user.id;
 const admin=await request(base,"/api/auth/login",{method:"POST",body:{email:"isolated-admin@example.invalid",password:"isolated-admin-password"}});
 assert.equal(admin.status,200,admin.text);
 const adminToken=JSON.parse(admin.text).token;
 const asset="/eight-pillars-review-stories.json";
 assert.equal((await request(base,asset)).status,401,"guest cannot access protected data");
 assert.equal((await request(base,asset,{token:memberToken})).status,401,"bearer alone cannot bypass browser session");
 assert.equal((await request(base,"/api/me/pan-african/browse-session",{method:"POST",token:memberToken})).status,403,"interested or ordinary member denied");
 assert.equal((await request(base,"/api/admin/pan-african/members/"+memberId,{method:"PUT",token:memberToken,body:{action:"approve"}})).status,403,"self approval denied");
 const approve=await request(base,"/api/admin/pan-african/members/"+memberId,{method:"PUT",token:adminToken,body:{action:"approve"}});
 assert.equal(approve.status,200,approve.text);
 const minted=await request(base,"/api/me/pan-african/browse-session",{method:"POST",token:memberToken});
 assert.equal(minted.status,200,minted.text);
 const url=new URL(JSON.parse(minted.text).enterUrl);
 const enter=await request(base,url.pathname+url.search);
 assert.equal(enter.status,303,enter.text);
 const cookie=enter.headers.get("set-cookie").split(";")[0];
 const content=await request(base,asset,{cookie});assert.equal(content.status,200,content.text.slice(0,300));
 assert.equal(content.headers.get("cache-control"),"private, no-store");
 const untouched=await request(base,"/api/pan-african/progress",{cookie});
 assert.equal(untouched.status,200);
 assert.equal(JSON.parse(untouched.text).progress,null,"approved membership does not auto-start a journey");
 const start=await request(base,"/api/pan-african/start",{method:"POST",cookie,body:{kind:"pillars"}});
 assert.equal(start.status,200,start.text);
 const saved=JSON.parse(start.text).progress;
 assert.match(saved.eightPillarsStart,/^\\d{4}-\\d{2}-\\d{2}$/);
 assert.equal(saved.combinedEightLimbsStart,undefined,"each journey starts independently");
 const again=await request(base,"/api/pan-african/start",{method:"POST",cookie,body:{kind:"pillars"}});
 assert.equal(JSON.parse(again.text).progress.eightPillarsStart,saved.eightPillarsStart,"repeat start cannot reset progress");
 assert.equal((await request(base,"/api/pan-african/start",{method:"POST",cookie,body:{kind:"unknown"}})).status,400);
 assert.equal((await request(base,url.pathname+url.search)).status,401,"single-use ticket cannot replay");
 const revoke=await request(base,"/api/admin/pan-african/members/"+memberId,{method:"PUT",token:adminToken,body:{action:"revoke"}});
 assert.equal(revoke.status,200,revoke.text);
 assert.equal((await request(base,asset,{cookie})).status,403,"revoked member loses already-issued browser grant");
 assert.equal((await request(base,"/api/pan-african/progress",{cookie})).status,401,"revocation also blocks progress");
});
